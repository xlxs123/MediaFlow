class MediaCheckError(ValueError):
    def __init__(self, message: str, code: str = 'MANIFEST_PARSE_ERROR', diagnostic: dict | None = None):
        super().__init__(message)
        self.code = code.value if isinstance(code, ErrorCode) else str(code)
        self.diagnostic = dict(diagnostic or {})
        self.diagnostic['error_code'] = self.code


class ProtectedMediaError(MediaCheckError):
    def __init__(self, message='检测到真正 DRM 受保护媒体，本工具不提供密钥提取或保护绕过功能。',
                 code='PROTECTED_MEDIA', diagnostic=None):
        super().__init__(message, code, diagnostic)


class MediaCheckCancelled(ValueError):
    pass
